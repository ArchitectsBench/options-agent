#!/usr/bin/env python3
"""Outage-day truth reconstruction — RECONSTRUCTED, NOT FORWARD EVIDENCE.

2026-08-03: Tradier's paper-trading backend 500'd every order placement
(status-page incident from 09:30 EDT). The agent DECIDED live all day —
signals, strikes, quantities, timestamps frozen in logs/recommendations.jsonl
BEFORE any outcome was knowable — but no order could fill. This script scores
those pre-committed decisions at ThetaData minute NBBO mids, simulating the
exit manager's mechanical rules.

WHY THIS IS NOT A BACKTEST: entries were generated by the live loop at
decision time (no hindsight in signal generation). Only EXECUTION is
counterfactual. Exit fidelity: invalidation uses the day's OWN live-logged
per-cycle vwap_dist_atr (computed in real time by the running agent);
stop_50 / target_50 / 15:45-ET flatten are evaluated on the truth minute
path sampled at the same 5-min cycle timestamps the live exit manager used.

WHY IT STILL DOESN'T COUNT: fills are assumed at mid (no queue, no
rejection, no slippage-at-entry) and exits are simulated, not lived. Output
is quarantined to its own file and NEVER enters fills.jsonl, the enriched
log, the CLL ledgers, or any forward-test count. Texture for the record of
what the outage cost — nothing more.

Run after the session + Theta availability:
  .venv/bin/python scripts/outage_reconstruction.py --date 2026-08-03 [--dry-run]
"""
from __future__ import annotations

import argparse
import importlib
import json
import re
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "scripts"))

STAMP = "RECONSTRUCTED — NOT FORWARD EVIDENCE (outage-day truth reconstruction)"
STOP_PCT, TARGET_PCT = 0.50, 0.50          # exit_manager.py frozen params
FLATTEN_ET = "15:45"


def load_attempted(day: str) -> list[dict]:
    """Today's live-decided TEST-lane recs that never filled (the outage set).
    Anchored on recommendations.jsonl (full trade spec, decided live) and
    cross-checked against fills.jsonl (must have NO fill)."""
    filled = set()
    fp = ROOT / "logs" / "observation" / "fills.jsonl"
    if fp.exists():
        for l in fp.read_text().splitlines():
            try:
                r = json.loads(l)
                if r.get("event") == "paper_fill":
                    filled.add(r["rec_id"])
            except Exception:
                continue
    out = []
    day8 = day.replace("-", "")
    for l in (ROOT / "logs" / "recommendations.jsonl").read_text().splitlines():
        try:
            r = json.loads(l)
        except Exception:
            continue
        rid = str(r.get("rec_id", ""))
        if not rid.startswith(day8) or rid in filled:
            continue
        t = r.get("trade") or {}
        if not t.get("legs"):
            continue
        qty = (r.get("risk") or {}).get("quantity") or r.get("quantity") or 1
        out.append({"rec_id": rid, "ticker": r.get("ticker"),
                    "strategy": t.get("strategy"), "structure": t.get("structure"),
                    "direction": t.get("direction"),
                    "legs": [{"symbol": lg["symbol"], "side": lg["action"]}
                             for lg in t["legs"]],
                    "qty": int(qty), "rec_net_debit": t.get("net_debit"),
                    "ts": r.get("generated") or r.get("generated_at") or r.get("ts") or ""})
    return out


def vwap_timeline(day: str) -> dict[str, list[tuple[str, float]]]:
    """ticker -> [(cycle_ts, vwap_dist_atr)] from the day's LIVE cycle log."""
    tl: dict[str, list] = {}
    f = ROOT / "logs" / "observation" / f"{day}.jsonl"
    if not f.exists():
        return tl
    for line in f.read_text().splitlines():
        try:
            r = json.loads(line)
        except Exception:
            continue
        ts = r.get("ts")
        sig = r.get("signals")
        items = sig.items() if isinstance(sig, dict) else []
        if not items and isinstance(sig, list):
            items = [(s.get("ticker"), s) for s in sig if isinstance(s, dict)]
        for tk, s in items:
            if isinstance(s, dict) and s.get("vwap_dist_atr") is not None and ts:
                tl.setdefault(tk, []).append((ts, s["vwap_dist_atr"]))
    for tk in tl:
        tl[tk].sort()
    return tl


def simulate(day: str, rec: dict, m, vt) -> dict | None:
    path = m.structure_path(rec["legs"], [day])
    if path is None:
        return {"rec_id": rec["rec_id"], "status": "no_market_data"}
    p = path.reset_index() if hasattr(path, "reset_index") else path
    mids = p["mid"] if "mid" in p else p.iloc[:, -1]
    tss = p["ts"] if "ts" in p else p.iloc[:, 0]
    ent_hm = (rec["ts"] or "")[11:16]
    if not ent_hm:
        return {"rec_id": rec["rec_id"], "status": "no_entry_ts"}
    # entry at the first minute mid at/after the decision minute (ET convert:
    # rec ts is PT; minute path is ET) — PT+3h
    h, mi = int(ent_hm[:2]) + 3, int(ent_hm[3:5])
    ent_et = f"{h:02d}:{mi:02d}"
    idx = [i for i, t in enumerate(tss) if str(t)[-5:] >= ent_et]
    if not idx:
        return {"rec_id": rec["rec_id"], "status": "entry_after_close"}
    i0 = idx[0]
    e = float(mids.iloc[i0])
    if e <= 0:
        return {"rec_id": rec["rec_id"], "status": "bad_entry_mid"}
    qty = rec["qty"]
    long_dir = (rec.get("direction") or "long") == "long"
    # walk 5-min cycle boundaries after entry
    exit_i, reason = None, None
    vseq = vt.get(rec["ticker"], [])
    for i in range(i0 + 1, len(mids)):
        hm = str(tss.iloc[i])[-5:]
        if hm >= FLATTEN_ET:
            exit_i, reason = i, "flatten_1545"
            break
        if int(hm[3:5]) % 5 != 0:
            continue                      # exits evaluated on cycle boundaries
        v = float(mids.iloc[i])
        if v <= e * (1 - STOP_PCT):
            exit_i, reason = i, "stop_50"; break
        if v >= e * (1 + TARGET_PCT):
            exit_i, reason = i, "target_50"; break
        # live-logged VWAP state at/just before this minute (PT clock in logs)
        pt_hm = f"{int(hm[:2])-3:02d}:{hm[3:5]}"
        vd = None
        for vts, vv in vseq:
            if vts[11:16] <= pt_hm:
                vd = vv
            else:
                break
        if vd is not None and ((long_dir and vd < 0) or (not long_dir and vd > 0)):
            exit_i, reason = i, "vwap_invalidation"; break
    if exit_i is None:
        exit_i, reason = len(mids) - 1, "eod"
    x = float(mids.iloc[exit_i])
    pnl = round((x - e) * 100 * qty, 2)
    return {"rec_id": rec["rec_id"], "ticker": rec["ticker"],
            "strategy": rec["strategy"], "qty": qty, "status": "ok",
            "entry_et": str(tss.iloc[i0])[-5:], "exit_et": str(tss.iloc[exit_i])[-5:],
            "entry_mid": round(e, 4), "exit_mid": round(x, 4),
            "exit_reason": reason, "truth_pnl": pnl, "stamp": STAMP}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", required=True)
    ap.add_argument("--dry-run", action="store_true", help="list the attempted set only")
    args = ap.parse_args()
    day = args.date
    if (not args.dry_run and day == datetime.now().strftime("%Y-%m-%d")
            and datetime.now().strftime("%H:%M") < "13:05"):
        print("session not complete — refusing to score before 13:05 PT")
        return 1
    recs = load_attempted(day)
    # de-dup per rec_id (retries share a rec_id only if re-recommended; keep all distinct ids)
    print(f"{len(recs)} live-decided, never-filled recs for {day}")
    for r in recs:
        print(f"  {r['rec_id'][-34:]:36} {r['ts'][11:16] if r['ts'] else '??:??'} "
              f"qty={r['qty']} net_debit={r['rec_net_debit']}")
    if args.dry_run:
        return 0
    m = importlib.import_module("enrich_trades_thetadata")
    vt = vwap_timeline(day)
    out_path = ROOT / "logs" / "observation" / f"outage_reconstruction-{day}.jsonl"
    rows, tot = [], 0.0
    with out_path.open("w") as f:
        for r in recs:
            row = simulate(day, r, m, vt)
            if row:
                f.write(json.dumps(row) + "\n")
                rows.append(row)
                if row.get("status") == "ok":
                    tot += row["truth_pnl"]
    ok = [r for r in rows if r.get("status") == "ok"]
    print(f"\nscored {len(ok)}/{len(rows)} | reconstructed truth P&L: ${tot:+.0f}")
    from collections import Counter
    print("exit reasons:", dict(Counter(r.get("exit_reason") for r in ok)))
    print(f"-> {out_path.name}  [{STAMP}]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
